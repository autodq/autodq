# Черновик слоя хранения AutoDQ.
#
# SourceRepository: хранить зарегистрированные источники с workspace_id и ссылкой
# на секрет. Учётные данные получать через выбранное хранилище секретов.
#
# DatasetReader: по идентификатору снимка подготовить прямоугольный набор строк
# и привести значения к формату autodq.table.Table. Для крупных источников
# сформировать воспроизводимую выборку, сохранив стратегию отбора, фильтр и seed.
#
# ProfileRepository: сохранять неизменяемые профили с версией схемы и ссылкой
# на исходный снимок. Ограничить доступ к частым значениям и словарям категорий.
#
# RuleBookRepository: хранить сгенерированные наборы правил по версиям.
# Решение пользователя сохранять с его идентификатором и причиной.
# Для конкурентного ревью проверять ожидаемую версию перед записью.
#
# CheckRepository: сохранять задание, его состояние, версию правил,
# параметры проверки и отчёт. При повторном запуске с тем же ключом
# идемпотентности возвращать уже созданное задание.
#
# ScheduleRepository: хранить часовой пояс, расписание и политику повторов.
# При обработке запуска по расписанию использовать уникальный ключ
# (schedule_id, planned_at), чтобы повторная доставка оставалась безопасной.
